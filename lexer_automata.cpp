int LexerAutomata::relaciona(char c){
    if (isalpha(c) && c != 'e' && c != 'E') return 0;
    if (isupper(c) && c != 'E') return 1;
    if(isdigit(c)) return 2;
    switch(c){
    case '_': return 3;
    case '.': return 4;
    case 'E': return 5;
    case 'e': return 6;
    case '+': return 7;
    case '-': return 8;
    case '=': return 9;
    case '<': return 10;
    case '>': return 11;
    case '!': return 12;
    case '&': return 13;
    case '|': return 14;
    case '\'': return 15;
    case '"': return 16;
    case '%': return 17;
    case '/': return 18;
    case '*': return 19;
    case '#': return 20;
    case '(': return 21;
    case ')': return 22;
    case '[': return 23;
    case ']': return 24;
    case ';': return 25;
    case ',': return 26;
    case '\t': return 28;
    case '\n': return 29;
    case ' ': return 30;
    default: return 27; //dif
    }

}




